package httpapi

// Ptr — небольшой generic-хелпер "взять указатель на значение", нужен из-за
// того, что сгенерированные oapi-codegen'ом типы (client.Venue, venue.Order
// и т.д.) делают необязательные по спеке поля указателями (`*string`,
// `*int64`...), а у нас в domain-слое они — обычные значения. Без этого
// хелпера пришлось бы заводить временную переменную под каждое поле
// (`v := x; ptr = &v`), что многословно.
func Ptr[T any](v T) *T {
	return &v
}
